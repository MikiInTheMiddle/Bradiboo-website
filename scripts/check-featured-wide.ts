import assert from 'node:assert/strict';
import {createElement} from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {FeaturedWide} from '../components/featured-wide';
import {resolveFeaturedSlide} from '../lib/featured-model';
import type {WireBlock} from '../lib/wireframe';
const inherited={label:'Episodio',href:'/guarda?contenuto=episodio#watch-player',description:'Sinossi',image:'/cover.jpg',badge:'Nuovo'};
assert.deepEqual(resolveFeaturedSlide(inherited,{label:'',description:undefined}),{...inherited,ctaLabel:'Guarda ora'});
assert.equal(resolveFeaturedSlide(inherited,{label:'Titolo locale'}).label,'Titolo locale');
assert.equal(inherited.label,'Episodio');
const first=resolveFeaturedSlide(inherited,{mobileImage:'/portrait.jpg',focalX:0});
const block:WireBlock={type:'media',title:'In primo piano',label:'Highlights',presentation:'wide',items:[first,{label:'Secondo',href:'/altro',badge:'In arrivo'}]};
const html=renderToStaticMarkup(createElement(FeaturedWide,{block}));
assert.ok(html.includes('aria-label="Mostra 1: Episodio"'));
assert.ok(html.includes('aria-label="Mostra 2: Secondo"'));
assert.ok(html.includes('/portrait.jpg'));
assert.ok(html.includes('object-position:0% 50%'));
assert.ok(html.includes('Sinossi'));
const single=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[first]}}));
assert.ok(!single.includes('featured-wide-dots'));
assert.ok(!single.includes('Contenuto successivo'));
const fallback=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,badge:'Etichetta globale da ignorare',items:[{label:'Senza etichetta',href:'/'}]}}));
assert.ok(fallback.includes('Highlights'));
assert.ok(!fallback.includes('Etichetta globale da ignorare'));
const standalone=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[],badge:'Etichetta del blocco',note:'Testo autonomo',backgroundMode:'page'}}));
assert.ok(standalone.includes('Testo autonomo'));
assert.ok(standalone.includes('Etichetta del blocco'));
assert.ok(!standalone.includes('featured-wide-dots'));
assert.ok(standalone.includes('background-color:transparent'));
const transparent=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[{...first,wideAppearance:{enabled:true,backgroundMode:'transparent'}}]}}));
assert.ok(!transparent.includes('featured-wide-picture'));
assert.ok(transparent.includes('background-color:transparent'));
assert.ok(!transparent.includes('background-color:#223668'));
const ctaMother=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[{...first,wideAppearance:{enabled:true,ctaBackgroundColor:'#ff0000'}}]}}));
assert.ok(!ctaMother.includes('#ff0000'));
assert.ok(fallback.indexOf('featured-wide-badge')<fallback.indexOf('featured-wide-viewport'));
const isolated=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,titleColor:'#ff0000',wideOverlayOpacity:99,items:[{...first,appearance:{enabled:true,titleColor:'#00ff00'},wideAppearance:{enabled:true,titleColor:'#123456',backgroundMode:'color',backgroundColor:'#abcdef',overlayOpacity:12}}]}}));
assert.ok(isolated.includes('#123456'));
assert.ok(isolated.includes('#abcdef'));
assert.ok(!isolated.includes('#ff0000'));
assert.ok(!isolated.includes('#00ff00'));
assert.ok(!isolated.includes('featured-wide-picture'));
assert.ok(isolated.includes('--wide-shade:0.12'));
console.log('OK: inheritance and local overrides, responsive picture, focal point, ordered dots and single-slide navigation.');

const {mergeWideAppearance}=await import('../lib/wide-appearance');
const labelOnly=mergeWideAppearance({enabled:false,badgeBackgroundColor:'#f9b400',backgroundColor:'#ff0000',backgroundMode:'color'});
assert.equal(labelOnly?.badgeBackgroundColor,'#f9b400');
assert.equal(labelOnly?.backgroundColor,undefined);
assert.equal(labelOnly?.backgroundMode,undefined);
const labelOnlyHtml=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[{...first,wideAppearance:labelOnly}]}}));
assert.ok(labelOnlyHtml.includes('--cookie-background:#f9b400'));
assert.ok(!labelOnlyHtml.includes('#ff0000'));
console.log('OK: slide label color independent of background/text override.');

const zeroVeil=renderToStaticMarkup(createElement(FeaturedWide,{block:{...block,items:[],backgroundMode:'image',backgroundImage:'/hero.jpg',mobileImage:'/hero-mobile.jpg',wideOverlayOpacity:0,focalX:0,focalY:100}}));
assert.ok(zeroVeil.includes('--wide-shade:0'));
assert.ok(zeroVeil.includes('object-position:0% 100%'));
assert.ok(zeroVeil.includes('/hero-mobile.jpg'));
const {cardSurfaceStyle}=await import('../lib/card-style');
assert.equal((cardSurfaceStyle({enabled:true,composition:'overlay',overlayOpacity:0}) as any)['--card-veil'],0);
console.log('OK: block and card zero veil, root focal point including 0%, mobile fallback.');
