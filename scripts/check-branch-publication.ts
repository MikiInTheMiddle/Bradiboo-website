import assert from 'node:assert/strict';
import {getPayload} from 'payload';
import config from '../payload.config';
import {branchPublication,hiddenBranchPath} from '../lib/branch-publication';
import {WatchNavigation} from '../components/watch-navigation';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,n){return s==='server-only'?{url:'data:text/javascript,export{}',shortCircuit:true}:n(s,c);}});
const {getCMSPage}=await import('../lib/cms');
assert.ok(process.env.DATABASE_URL?.includes('/tmp/'),'Disposable DB required');
const p=await getPayload({config});
try{
 const container=(await p.find({collection:'production-containers',where:{slug:{equals:'serie'}},depth:0})).docs[0];assert.ok(container);
 const prod=(await p.find({collection:'contents',where:{and:[{container:{equals:container.id}},{recordType:{equals:'production'}}]},depth:0})).docs[0];assert.ok(prod);
 const children=(await p.find({collection:'contents',where:{container:{equals:container.id}},limit:1000,depth:0})).docs;
 const statuses=children.map(c=>[c.id,c._status]);
 const publicContents=()=>p.find({collection:'contents',where:{container:{equals:container.id}},limit:1000,depth:0,overrideAccess:false});
 assert.ok((await publicContents()).docs.length);
 await p.update({collection:'production-containers',id:container.id,data:{showInExplore:false}});
 let menu=await WatchNavigation({currentPath:'/guarda',children:null});assert.ok(!menu.props.containers.some((c:any)=>c.id===container.id));
 assert.ok((await publicContents()).docs.length,'Menu-only hide must not hide content');
 await p.update({collection:'production-containers',id:container.id,data:{showInExplore:true,_status:'draft'}});
 assert.equal((await publicContents()).docs.length,0);
 assert.equal((await p.find({collection:'production-containers',where:{id:{equals:container.id}},overrideAccess:false})).docs.length,0);
 assert.equal((await p.find({collection:'pages',where:{path:{equals:prod.url!}},overrideAccess:false})).docs.length,0);
 assert.equal(await getCMSPage(prod.url!),undefined,'Frontend preview must also respect disabled branch');
 let state=await branchPublication(p);assert.ok(hiddenBranchPath(prod.url!,state));
 const home=await getCMSPage('/');assert.ok(home);assert.ok(!home.blocks.flatMap(b=>b.items||[]).some(i=>hiddenBranchPath(i.href,state)),'Manual and automatic Home cards must both respect hidden branch');
 assert.deepEqual((await p.find({collection:'contents',where:{container:{equals:container.id}},limit:1000,depth:0})).docs.map(c=>[c.id,c._status]),statuses);
 await p.update({collection:'production-containers',id:container.id,data:{_status:'published'}});
 assert.ok((await publicContents()).docs.some(c=>c.id===prod.id));
 await p.update({collection:'contents',id:prod.id,data:{showInExplore:false}});
 menu=await WatchNavigation({currentPath:'/guarda',children:null});assert.ok(!menu.props.containers.flatMap((c:any)=>c.productions).some((c:any)=>c.id===prod.id));
 assert.ok((await publicContents()).docs.some(c=>c.id===prod.id));
 await p.update({collection:'contents',id:prod.id,data:{_status:'draft'}});
 assert.ok(!(await publicContents()).docs.some(c=>c.id===prod.id||Number(typeof c.parent==='object'?c.parent?.id:c.parent)===prod.id));
 assert.equal(await getCMSPage(prod.url!),undefined);
 await p.update({collection:'contents',id:prod.id,data:{_status:'published',showInExplore:true}});
 assert.deepEqual((await p.find({collection:'contents',where:{container:{equals:container.id}},limit:1000,depth:0})).docs.map(c=>[c.id,c._status]),statuses);
 assert.ok(await getCMSPage(prod.url!));
 console.log('OK: container and production branches hide publicly, pages and menus follow, children keep their states, republishing restores, menu-only visibility stays independent.');
}finally{await p.destroy()}
