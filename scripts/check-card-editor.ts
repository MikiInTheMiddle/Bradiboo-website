import assert from 'node:assert/strict';
import config from '../payload.config';
import {findEditorFields,cardEditorPanels,flatEditorFields} from '../lib/card-editor-model';
const schema=await config;const pages=schema.collections!.find(c=>c.slug==='pages')!;
const rows=findEditorFields(pages.fields,'pages','pages.blocks.grid.items');assert.ok(rows);
const regular=cardEditorPanels(rows,false,false);
assert.deepEqual(regular.panels.map(p=>p.label),['Contenuto','Media','Fondo','Etichetta','Hover']);
const mobileMedia=regular.panels.find(p=>p.id==='media')!.fields;
const hasMobile=(values:any[]):boolean=>values.some(f=>f.name==='mobileImage'||f.fields&&hasMobile(f.fields));
assert.ok(hasMobile(mobileMedia),'Default cards expose the mobile override in Media');
const wide=cardEditorPanels(rows,false,true);
assert.deepEqual(wide.panels.map(p=>p.label),['Contenuto','Fondo','Etichetta','Hover']);
const flattened=(values:any[]):any[]=>values.flatMap(f=>[f,...(f.fields?flattened(f.fields):[])]);
assert.ok(!flattened(wide.panels[0].fields).some(f=>['image','mobileImage','focalX','focalY'].includes(f.name)));
const background=flattened(wide.panels.find(p=>p.id==='background')!.fields);
for(const name of ['overlayOpacity','backgroundImageControl','focalX','focalY','mobileImage'])assert.ok(background.some(f=>f.name===name),name);
const slide=cardEditorPanels(rows,true,true);
assert.ok(!slide.panels.some(p=>p.id==='hover'));
assert.ok(flattened(slide.panels.find(p=>p.id==='label')!.fields).some(f=>f.name==='labelControl'));
for(const panel of [...regular.panels,...wide.panels,...slide.panels])assert.ok(!panel.fields.some(f=>f.admin?.hidden),'Root fields restored in UI projection');
const rootBlocks=flatEditorFields(pages.fields).find(f=>f.type==='blocks');
const hero=rootBlocks.blocks.find((b:any)=>b.slug==='hero');
for(const name of ['wideOverlayOpacity','focalX','focalY','mobileImage'])assert.ok(flatEditorFields(hero.fields).some(f=>f.name===name),name);
console.log('OK: flat Default/Wide card editor, images/focus/veil grouped in Fondo, separate default media and hover, canonical paths retained.');
